/**
 * Builds graph/lineage.json: nodes, typed edges, and an adjacency list that an agent
 * can walk in both directions. Fails if an edge points at a style that does not exist.
 */
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { EVIDENCE_WEIGHT, loadCues, loadEmotions, loadEvokes, loadMoments } from "./emotions.js";
import { loadLayer, styleLinks } from "./materials.js";
import { ROOT, loadAll, loadFunding, loadOrgs, loadPeople, loadTechniques, nearest, write, type Style } from "./lib.js";

type EdgeType = "EVOLVED_FROM" | "REBELLED_AGAINST" | "HYBRIDIZED_WITH" | "ECHOES" | "SUBGENRE_OF";
interface Edge { from: string; to: string; type: EdgeType }

const { domains, eras, styles } = loadAll();
const byId = new Map<string, Style>(styles.map((s) => [s.id, s]));
const edges = new Map<string, Edge>();
const broken: string[] = [];

const add = (from: string, to: string, type: EdgeType, symmetric: boolean) => {
  if (!byId.has(to)) return void broken.push(`${from} —${type}→ ${to}`);
  // A symmetric edge is stored once, with the ids in alphabetical order.
  const [a, b] = symmetric && from > to ? [to, from] : [from, to];
  edges.set(`${type}|${a}|${b}`, { from: a, to: b, type });
};

for (const s of styles) {
  for (const t of s.lineage.evolved_from) add(s.id, t, "EVOLVED_FROM", false);
  for (const t of s.lineage.rebelled_against) add(s.id, t, "REBELLED_AGAINST", false);
  for (const t of s.lineage.hybridized_with) add(s.id, t, "HYBRIDIZED_WITH", true);
  for (const t of s.lineage.echoes ?? []) add(s.id, t, "ECHOES", true);
  if (s.lineage.subgenre_of) add(s.id, s.lineage.subgenre_of, "SUBGENRE_OF", false);
}

if (broken.length) {
  for (const b of broken) console.error(`error broken edge: ${b}`);
  process.exit(1);
}

const edgeList = [...edges.values()].sort(
  (a, b) => a.type.localeCompare(b.type) || a.from.localeCompare(b.from) || a.to.localeCompare(b.to),
);

const empty = () => ({
  evolved_from: [] as string[],
  evolved_into: [] as string[],
  rebelled_against: [] as string[],
  provoked: [] as string[],
  hybridized_with: [] as string[],
  echoes: [] as string[],
  subgenre_of: [] as string[],
  subgenres: [] as string[],
  nearest_by_vector: [] as { id: string; distance: number }[],
  techniques: [] as string[],
});
const adjacency: Record<string, ReturnType<typeof empty>> = {};
for (const s of styles) adjacency[s.id] = empty();

for (const e of edgeList) {
  if (e.type === "EVOLVED_FROM") {
    adjacency[e.from].evolved_from.push(e.to);
    adjacency[e.to].evolved_into.push(e.from);
  } else if (e.type === "REBELLED_AGAINST") {
    adjacency[e.from].rebelled_against.push(e.to);
    adjacency[e.to].provoked.push(e.from);
  } else if (e.type === "SUBGENRE_OF") {
    adjacency[e.from].subgenre_of.push(e.to);
    adjacency[e.to].subgenres.push(e.from);
  } else {
    const key = e.type === "HYBRIDIZED_WITH" ? "hybridized_with" : "echoes";
    adjacency[e.from][key].push(e.to);
    adjacency[e.to][key].push(e.from);
  }
}
for (const s of styles) {
  const axes = domains.find((d) => d.id === s.domain)!.vectors;
  adjacency[s.id].nearest_by_vector = nearest(s, styles, axes);
  for (const [k, v] of Object.entries(adjacency[s.id])) if (k !== "nearest_by_vector") (v as string[]).sort();
}

const techniques = loadTechniques().map(({ technique: t }) => ({
  id: t.id,
  name: t.name,
  kind: t.kind,
  origin: { domain: t.origin.domain, year: t.origin.year, circa: t.origin.circa ?? false },
  adoptions: t.adoptions.map((a) => ({
    domain: a.domain,
    year: a.year,
    circa: a.circa ?? false,
    lag_years: a.year - t.origin.year,
    styles: a.styles ?? [],
  })),
  styles: t.styles,
}));
for (const t of techniques)
  for (const id of t.styles) {
    if (!adjacency[id]) {
      console.error(`error technique ${t.id} → unknown style ${id}`);
      process.exit(1);
    }
    adjacency[id].techniques.push(t.id);
  }
for (const a of Object.values(adjacency)) a.techniques.sort();

const graph = {
  $comment: "Generated by scripts/build-graph.ts. Do not edit by hand.",
  edge_types: {
    EVOLVED_FROM: "from is a descendant of to. Inverse in adjacency: evolved_into.",
    REBELLED_AGAINST: "from rejects to. Inverse in adjacency: provoked.",
    HYBRIDIZED_WITH: "Symmetric. The two styles mix in practice.",
    ECHOES: "Symmetric. Kin across two domains.",
    SUBGENRE_OF: "from is a narrower branch of to, in the same domain. Inverse in adjacency: subgenres.",
  },
  domains: domains.map((d) => ({ id: d.id, name: d.name, axes: d.vectors.map((v) => v.key) })),
  nodes: styles.map((s) => ({
    id: s.id,
    domain: s.domain,
    name: s.name,
    era: s.era_id,
    start: s.time_period.start,
    end: s.time_period.end,
    vectors: s.vectors,
  })),
  edges: edgeList,
  techniques,
  adjacency,
};

write("graph/lineage.json", JSON.stringify(graph, null, 2));
console.log(`graph/lineage.json · ${graph.nodes.length} nodes · ${edgeList.length} edges · ${techniques.length} techniques`);

// ── People: each life next to the spans of the styles it touched ────────────
const people = loadPeople()
  .map(({ person: p }) => {
    // A posthumous milestone (a dig, a museum sale) is not a year of the life, so it does not set the active span.
    const years = p.milestones.filter((m) => !m.posthumous).map((m) => m.year);
    return {
      id: p.id,
      name: p.name,
      born: p.born,
      died: p.died,
      // The first and the last dated milestone of the life. The time line uses it when no born year is known.
      active: years.length ? [Math.min(...years), Math.max(...years)] : null,
      // The lane on the time line: the domain of the first style. Unplaced when there is no style.
      domain: byId.get(p.styles[0]?.style ?? "")?.domain ?? "unplaced",
      nationality: p.nationality ?? [],
      bio: p.bio,
      photo: p.photo ? { url: p.photo.url, page: p.photo.page, licence: p.photo.licence, credit: p.photo.credit } : null,
      wikidata: p.identity?.wikidata ?? null,
      styles: p.styles,
      milestones: [...p.milestones].sort((a, b) => a.year - b.year),
    };
  })
  .sort((a, b) => (a.born ?? a.active![0] - 30) - (b.born ?? b.active![0] - 30) || a.id.localeCompare(b.id));
const byStyle: Record<string, { person: string; role: string }[]> = {};
for (const s of styles) byStyle[s.id] = [];
for (const p of people) for (const s of p.styles) byStyle[s.style]?.push({ person: p.id, role: s.role });
write(
  "graph/people.json",
  JSON.stringify({ $comment: "Generated by scripts/build-graph.ts from data/people/. Do not edit by hand.", people, by_style: byStyle }, null, 2),
);
console.log(`graph/people.json · ${people.length} people · ${Object.values(byStyle).filter((v) => !v.length).length} styles with no person`);

// ── Organisations: groups, channels and backers, with their styles, members and relations ──
const orgs = loadOrgs()
  .map(({ org: o }) => ({
    id: o.id,
    name: o.name,
    kind: o.kind,
    founded: o.founded,
    closed: o.closed,
    place: o.place,
    summary: o.summary,
    wikidata: o.identity?.wikidata ?? null,
    styles: o.styles,
    people: o.people ?? [],
    members: o.members ?? [],
    statement: o.statement ?? null,
    moves: [...(o.moves ?? [])].sort((a, b) => a.year - b.year),
    relations: o.relations ?? {},
  }))
  .sort((a, b) => (a.founded ?? 9999) - (b.founded ?? 9999) || a.id.localeCompare(b.id));
const orgsByStyle: Record<string, { org: string; part: string }[]> = {};
for (const s of styles) orgsByStyle[s.id] = [];
for (const o of orgs) for (const s of o.styles) orgsByStyle[s.style]?.push({ org: o.id, part: s.part });
const orgsByPerson: Record<string, { org: string; role: string }[]> = {};
for (const o of orgs) {
  for (const m of o.members) (orgsByPerson[m.person] ??= []).push({ org: o.id, role: m.role });
  for (const p of o.people) if (!o.members.some((m) => m.person === p)) (orgsByPerson[p] ??= []).push({ org: o.id, role: "ran" });
}
// Relations between organisations. rival_of is symmetric and is stored once.
const orgEdges = new Map<string, { from: string; to: string; type: string }>();
for (const o of orgs)
  for (const [rel, ids] of Object.entries(o.relations))
    for (const t of ids ?? []) {
      const type = rel.toUpperCase();
      const [a, b] = rel === "rival_of" && o.id > t ? [t, o.id] : [o.id, t];
      orgEdges.set(`${type}|${a}|${b}`, { from: a, to: b, type });
    }
write(
  "graph/orgs.json",
  JSON.stringify(
    {
      $comment: "Generated by scripts/build-graph.ts from data/orgs/. Do not edit by hand.",
      edge_types: {
        MEMBER_OF: "from is a member body of to (a group inside a council).",
        SPLIT_FROM: "from was founded by people who left to.",
        SUCCESSOR_OF: "from took over the work of to.",
        RIVAL_OF: "Symmetric. The two fought for the same ground.",
      },
      orgs,
      edges: [...orgEdges.values()].sort((a, b) => a.type.localeCompare(b.type) || a.from.localeCompare(b.from) || a.to.localeCompare(b.to)),
      by_style: orgsByStyle,
      by_person: orgsByPerson,
    },
    null,
    2,
  ),
);
console.log(`graph/orgs.json · ${orgs.length} orgs · ${orgEdges.size} relations · ${Object.values(orgsByStyle).filter((v) => !v.length).length} styles with no org`);

// ── Money: who paid whom, when, for what ──────────────────────────────────────
// Each flow is an edge from a backer (a person or an organisation) to a style, a person or an
// organisation. by_style collects the flows that reached a style, directly or through `styles`.
const flows = loadFunding()
  .map(({ funding: f }) => ({
    id: f.id,
    from: f.from,
    to: f.to,
    styles: f.to.type === "style" ? [f.to.id] : (f.styles ?? []),
    kind: f.kind,
    years: f.years,
    what: f.what,
    amount: f.amount ?? null,
    confidence: f.confidence,
    sources: f.sources,
  }))
  .sort((a, b) => a.years[0] - b.years[0] || a.id.localeCompare(b.id));
const moneyByStyle: Record<string, string[]> = {};
for (const s of styles) moneyByStyle[s.id] = [];
for (const f of flows) for (const s of f.styles) moneyByStyle[s]?.push(f.id);
const moneyByBacker: Record<string, string[]> = {};
for (const f of flows) (moneyByBacker[`${f.from.type}:${f.from.id}`] ??= []).push(f.id);
write(
  "graph/money.json",
  JSON.stringify(
    {
      $comment: "Generated by scripts/build-graph.ts from data/funding/. Do not edit by hand.",
      flows,
      by_style: moneyByStyle,
      by_backer: moneyByBacker,
    },
    null,
    2,
  ),
);
console.log(`graph/money.json · ${flows.length} flows · ${Object.keys(moneyByBacker).length} backers · ${Object.values(moneyByStyle).filter((v) => v.length).length} styles with money`);

// ── The emotions layer: terms with PAD points, and carriers ranked for each emotion ──
const emotions = loadEmotions().map(({ emotion: e }) => ({ id: e.id, name: e.name, family: e.family, culture: e.culture, pad: { p: e.pad.p, a: e.pad.a, d: e.pad.d }, nearest: e.nearest, opposite: e.opposite }));
type Carried = { carrier: string; id: string; domain: string | null; strength: number; evidence: string; score: number };
const byEmotion: Record<string, Carried[]> = Object.fromEntries(emotions.map((e) => [e.id, []]));
const evokesByStyle: Record<string, { emotion: string; strength: number; evidence: string }[]> = {};
for (const { evokes: f } of loadEvokes())
  for (const [id, list] of Object.entries(f.edges))
    for (const e of list) {
      // The best evidence of an edge sets its kind and its weight.
      const best = (["measured", "stated", "inferred"] as const).find((k) => e.evidence.some((x) => x.kind === k))!;
      const score = Math.round(e.strength * EVIDENCE_WEIGHT[best] * 100) / 100;
      byEmotion[e.emotion]?.push({ carrier: f.carrier, id, domain: f.domain, strength: e.strength, evidence: best, score });
      if (f.carrier === "style") (evokesByStyle[id] ??= []).push({ emotion: e.emotion, strength: e.strength, evidence: best });
    }
for (const list of Object.values(byEmotion)) list.sort((a, b) => b.score - a.score || a.id.localeCompare(b.id));
// Cues by emotion: a cue that names an emotion lists under it. A cue on a PAD axis lists under pad:p, pad:a or pad:d.
type CueRef = { cue: string; variable: string; change: string; unit: string; range: { from: number | string; to: number | string }; sign: 1 | -1; size: string; weak: boolean };
const cues = loadCues().map(({ cue }) => cue);
const cuesByEmotion: Record<string, CueRef[]> = {};
for (const c of cues)
  for (const e of c.effects)
    (cuesByEmotion[e.target] ??= []).push({ cue: c.id, variable: c.variable, change: c.direction.change, unit: c.direction.unit, range: c.direction.range, sign: e.sign, size: e.size, weak: c.weak ?? false });
for (const list of Object.values(cuesByEmotion)) list.sort((a, b) => Number(a.weak) - Number(b.weak) || a.cue.localeCompare(b.cue));
// Moments by emotion, strongest first.
const moments = loadMoments().map(({ moment }) => moment);
const momentsByEmotion: Record<string, { moment: string; kind: string; strength: number }[]> = {};
for (const m of moments) for (const e of m.emotions) (momentsByEmotion[e.emotion] ??= []).push({ moment: m.id, kind: m.kind, strength: e.strength });
for (const list of Object.values(momentsByEmotion)) list.sort((a, b) => b.strength - a.strength || a.moment.localeCompare(b.moment));
const momentIndex = Object.fromEntries(
  moments.map((m) => [m.id, { name: m.name, kind: m.kind, emotions: m.emotions, time: m.time, light: m.light, weather: m.weather, people: m.people, carriers: m.carriers, cues: m.cues, scene_ref: m.scene_ref }]),
);
write(
  "graph/emotions.json",
  JSON.stringify(
    {
      $comment: "Generated by scripts/build-graph.ts from data/emotions/, data/evokes/, data/cues/ and data/moments/. Do not edit by hand. score = strength × evidence weight (measured 1, stated 0.7, inferred 0.3).",
      emotions,
      by_emotion: byEmotion,
      by_style: evokesByStyle,
      cues_by_emotion: Object.fromEntries(Object.entries(cuesByEmotion).sort(([a], [b]) => a.localeCompare(b))),
      moments_by_emotion: Object.fromEntries(Object.entries(momentsByEmotion).sort(([a], [b]) => a.localeCompare(b))),
      moments: momentIndex,
    },
    null,
    2,
  ),
);
console.log(`graph/emotions.json · ${emotions.length} emotions · ${Object.values(byEmotion).reduce((n, l) => n + l.length, 0)} edges · ${styles.filter((s) => !evokesByStyle[s.id]).length} styles with no emotion · ${cues.length} cues · ${moments.length} moments`);


// ── The material layer: nodes, process edges, tools, and the derived links to styles ──────────────────────────────
const M = loadLayer();
if (M.byId.size) {
  const { links, processes, unmatched } = styleLinks(M);
  const photo = (id: string) => (existsSync(join(ROOT, "demo", "materials", "photos", `${id}.webp`)) ? `materials/photos/${id}.webp` : null);
  const procNames = new Map<string, string>();
  for (const t of techniques) procNames.set(`technique:${t.id}`, t.name);
  for (const d of ["cuisine.methods", "ceramics.decorations", "fashion.finishes", "industrial.finishes"]) {
    const [domain, list] = d.split(".");
    const v = JSON.parse(readFileSync(join(ROOT, "data", domain, "vocabulary.json"), "utf8")) as Record<string, { id: string; name: string }[]>;
    for (const e of v[list] ?? []) procNames.set(`${d}:${e.id}`, e.name);
  }
  write(
    "graph/materials.json",
    JSON.stringify(
      {
        classes: M.classes.map(({ data: c }) => ({ id: c.class, name: c.name, summary: c.summary, families: c.families })),
        materials: [...M.byId.values()].map((m) => ({ ...m, photo: photo(m.id) })),
        tools: [...M.tools.values()],
        processes: M.edges.map(({ edge }) => ({ ...edge, name: procNames.get(edge.process) ?? edge.process })),
        styles: Object.fromEntries(styles.map((s) => [s.id, { name: s.name, domain: s.domain }])),
        style_materials: links,
        style_processes: processes.filter((p) => procNames.has(p.process)),
        unmatched,
      },
      null,
      1,
    ),
  );
  console.log(`graph/materials.json · ${M.byId.size} materials · ${M.edges.length} processes · ${links.length} style links · ${unmatched.length} free-text strings with no material`);
}

// ── Mermaid picture of the lineage, for people ──────────────────────────────
// Hybrid edges are left out of the picture: they are many, and they hide the two edges that carry the history.
const mm: string[] = ["flowchart LR"];
const node = (id: string) => id.replace(/-/g, "_");
for (const d of domains) {
  for (const era of [...eras.values()].filter((e) => e.domain === d.id)) {
    const own = styles.filter((s) => s.domain === d.id && s.era_id === era.id);
    if (!own.length) continue;
    mm.push(`  subgraph ${node(d.id)}_${node(era.id)}["${d.id === "internet" ? "" : d.name + " · "}${era.name} · ${era.period}"]`);
    for (const s of own) mm.push(`    ${node(s.id)}["${s.name}"]`);
    mm.push("  end");
  }
}
const drawn = edgeList.filter((e) => e.type !== "HYBRIDIZED_WITH");
for (const e of drawn) {
  if (e.type === "EVOLVED_FROM") mm.push(`  ${node(e.to)} --> ${node(e.from)}`);
  else if (e.type === "REBELLED_AGAINST") mm.push(`  ${node(e.from)} -. rejects .-> ${node(e.to)}`);
  else if (e.type === "SUBGENRE_OF") mm.push(`  ${node(e.to)} == branch ==> ${node(e.from)}`);
  else mm.push(`  ${node(e.from)} <-. echoes .-> ${node(e.to)}`);
}
drawn.forEach((e, i) => {
  if (e.type === "REBELLED_AGAINST") mm.push(`  linkStyle ${i} stroke:#E5484D,stroke-width:1.5px`);
  if (e.type === "ECHOES") mm.push(`  linkStyle ${i} stroke:#8E8E93,stroke-width:1.5px`);
});
const mermaid = mm.join("\n");
write("graph/lineage.mmd", mermaid);

const readme = join(ROOT, "README.md");
if (existsSync(readme)) {
  const text = readFileSync(readme, "utf8");
  const next = text.replace(
    /(<!-- lineage:start -->)[\s\S]*?(<!-- lineage:end -->)/,
    `$1\n\`\`\`mermaid\n${mermaid}\n\`\`\`\n$2`,
  );
  if (next !== text) write("README.md", next);
}
